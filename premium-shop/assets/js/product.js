/**
 * Premium Shop — product page: "Buy now", sticky mobile add-to-cart bar,
 * product video modal.
 */
(function () {
	'use strict';

	var doc = document;
	var PS = window.PremiumShop || {};

	function $(sel, ctx) { return (ctx || doc).querySelector(sel); }

	var form = $('form.cart');
	var addButton = form ? $('.single_add_to_cart_button', form) : null;

	/* ------------------------------------------------------------------
	 * Buy now: mirror the state of "Add to cart" (variations).
	 * ------------------------------------------------------------------ */
	var buyNow = form ? $('[data-ps-buy-now]', form) : null;
	if (buyNow && addButton) {
		var sync = function () {
			var disabled = addButton.classList.contains('disabled');
			buyNow.classList.toggle('disabled', disabled);
			buyNow.setAttribute('aria-disabled', disabled ? 'true' : 'false');
		};
		sync();
		if (window.MutationObserver) {
			new MutationObserver(sync).observe(addButton, { attributes: true, attributeFilter: ['class'] });
		}
		buyNow.addEventListener('click', function (e) {
			if (buyNow.classList.contains('disabled')) {
				e.preventDefault();
				addButton.click(); // Lets WooCommerce show its "choose options" message.
			}
		});
	}

	/* ------------------------------------------------------------------
	 * Sticky add-to-cart bar (mobile)
	 * ------------------------------------------------------------------ */
	var bar = $('[data-ps-sticky-cart]');
	if (bar && form && 'IntersectionObserver' in window) {
		bar.hidden = false;
		new IntersectionObserver(function (entries) {
			var entry = entries[0];
			var past = !entry.isIntersecting && entry.boundingClientRect.top < 0;
			bar.classList.toggle('is-visible', past);
		}).observe(form);

		var barBtn = $('[data-ps-sticky-cart-btn]', bar);
		if (barBtn) {
			barBtn.addEventListener('click', function () {
				var needsChoice = form.classList.contains('variations_form') || form.classList.contains('grouped_form');
				if (!needsChoice && addButton) {
					addButton.click();
					return;
				}
				form.scrollIntoView({ behavior: 'smooth', block: 'center' });
				var first = form.querySelector('select, input:not([type="hidden"])');
				if (first) { setTimeout(function () { first.focus({ preventScroll: true }); }, 450); }
			});
		}
	}

	/* ------------------------------------------------------------------
	 * Gallery thumbnails (generated by WooCommerce's slider) need alt text.
	 * ------------------------------------------------------------------ */
	var title = $('.product_title');
	function labelThumbs() {
		var thumbs = document.querySelectorAll('.flex-control-thumbs img:not([alt])');
		Array.prototype.forEach.call(thumbs, function (img, i) {
			img.setAttribute('alt', (title ? title.textContent.trim() + ' – ' : '') + (i + 1));
		});
	}
	labelThumbs();
	window.addEventListener('load', labelThumbs);
	if (window.jQuery) { window.jQuery('.woocommerce-product-gallery').on('wc-product-gallery-after-init', labelThumbs); }

	/* ------------------------------------------------------------------
	 * Product video (loaded only on demand)
	 * ------------------------------------------------------------------ */
	var videoBtn = $('[data-ps-video]');
	var videoTpl = $('template[data-ps-video-template]');
	if (videoBtn && videoTpl && PS.modal && PS.modalContent) {
		videoBtn.addEventListener('click', function () {
			PS.modal.classList.add('ps-modal--video');
			PS.modalContent.classList.remove('is-loading');
			PS.modalContent.innerHTML = '';
			PS.modalContent.appendChild(videoTpl.content.cloneNode(true));
			PS.openDrawer(PS.modal, videoBtn);
			var media = PS.modalContent.querySelector('video');
			if (media && media.play) {
				var p = media.play();
				if (p && p.catch) { p.catch(function () {}); }
			}
		});
		doc.addEventListener('ps:drawer-close', function (e) {
			if (e.detail.el === PS.modal) { PS.modal.classList.remove('ps-modal--video'); }
		});
	}
}());
